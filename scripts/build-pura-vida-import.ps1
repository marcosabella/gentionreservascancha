$ErrorActionPreference = 'Stop'
$schemaPath = Join-Path $PSScriptRoot '../supabase/pura-vida-public-schema.sql'
$inventoryPath = Join-Path $PSScriptRoot '../supabase/pura-vida-source-inventory.json'
$schemaText = [System.IO.File]::ReadAllText($schemaPath)
$inventory = (Get-Content -Raw $inventoryPath | ConvertFrom-Json).rows[0].inventory
if (@($inventory.tables).Count -ne 16) { throw 'Unexpected source inventory.' }
if ($schemaText -match '(?m)^COPY .* FROM stdin;' -or $schemaText -match '(?m)^INSERT INTO ') {
  throw 'Export contains data statements.'
}
$header = @'
-- Pura Vida: schema only, no customer records, users, or configuration rows.
-- Source: zcixnnzxxkylotbjudhk. Intended destination: qsvdpdifygmzdawxfyqv.
-- Existing source access policies are preserved; this is not a security remediation.
-- Import is atomic and refuses a destination with existing public tables or users.
BEGIN;
DO $guard$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_tables WHERE schemaname='public') THEN
    RAISE EXCEPTION 'Destination public schema must be empty';
  END IF;
  IF EXISTS (SELECT 1 FROM auth.users) THEN
    RAISE EXCEPTION 'Destination authentication users must be empty';
  END IF;
END;
$guard$;

'@
$authTriggers = @($inventory.triggers | Where-Object schema -eq 'auth' | ForEach-Object { $_.definition + ';' }) -join "`n"
# The CLI's sed filter removes SQL comment lines even inside function bodies.
# Restore catalog definitions so function text matches the source exactly.
$functionDefinitions = @($inventory.functions | ForEach-Object { $_.definition.TrimEnd() + ';' }) -join "`n"
$footer = @'

-- Verify that no rows were imported or generated by the schema deployment.
DO $verify$
DECLARE
  target_table record;
  row_count bigint;
BEGIN
  IF (SELECT count(*) FROM pg_tables WHERE schemaname='public') <> 16 THEN
    RAISE EXCEPTION 'Unexpected application table count';
  END IF;
  FOR target_table IN SELECT tablename FROM pg_tables WHERE schemaname='public' LOOP
    EXECUTE format('SELECT count(*) FROM public.%I', target_table.tablename) INTO row_count;
    IF row_count <> 0 THEN
      RAISE EXCEPTION 'Unexpected records in table %', target_table.tablename;
    END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM auth.users) THEN
    RAISE EXCEPTION 'Unexpected authentication users';
  END IF;
END;
$verify$;
SELECT pg_notify('pgrst', 'reload schema');
COMMIT;
'@
$outputPath = Join-Path $PSScriptRoot '../supabase/pura-vida-schema.sql'
[System.IO.File]::WriteAllText($outputPath, $header + "`n" + $schemaText + "`nSET LOCAL search_path = public, pg_catalog;`n" + $functionDefinitions + "`n" + $authTriggers + "`n" + $footer + "`n", [System.Text.UTF8Encoding]::new($false))
$functionPath = Join-Path $PSScriptRoot '../supabase/pura-vida-function-definitions.sql'
[System.IO.File]::WriteAllText($functionPath, "BEGIN;`n" + $functionDefinitions + "`nCOMMIT;`n", [System.Text.UTF8Encoding]::new($false))
Write-Output ('Prepared atomic schema-only import with {0} auth trigger(s).' -f @($inventory.triggers | Where-Object schema -eq 'auth').Count)
