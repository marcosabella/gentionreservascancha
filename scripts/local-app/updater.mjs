import { mkdir, readFile, readdir, rename, rm, writeFile } from 'node:fs/promises';
import { basename, dirname, join, resolve } from 'node:path';
import { randomUUID } from 'node:crypto';
import { APP_ID, MANIFEST_NAME, RELEASE_ORIGIN, digest, validateManifest, verifyReleaseDirectory } from './release-manifest.mjs';

const summary = manifest => ({ version: manifest.version, publishedAt: manifest.publishedAt, notes: manifest.notes });
const validDirectory = value => value === 'bundled' || typeof value === 'string' && /^[a-f0-9-]{36}$/.test(value);

export async function createUpdater({ root, source = RELEASE_ORIGIN, fetchImpl = fetch, timeoutMs = 30000, checkIntervalMs = 60000 }) {
  const base = resolve(root);
  const sourceUrl = new URL(source);
  if (sourceUrl.protocol !== 'https:' && !['localhost', '127.0.0.1'].includes(sourceUrl.hostname)) throw new Error('Origen de actualizaciones inválido.');
  const storage = join(base, '.local-updates');
  const releaseRoot = join(storage, 'releases');
  const stateFile = join(storage, 'state.json');
  await mkdir(releaseRoot, { recursive: true });
  const directoryFor = name => {
    if (!validDirectory(name)) throw new Error('Versión local inválida.');
    return name === 'bundled' ? join(base, 'app') : join(releaseRoot, name);
  };
  async function loadRelease(name) {
    const directory = directoryFor(name);
    const manifest = validateManifest(JSON.parse(await readFile(join(directory, MANIFEST_NAME), 'utf8')));
    await verifyReleaseDirectory(directory, manifest);
    return { name, directory, manifest };
  }
  const bundled = await loadRelease('bundled');
  const archived = [];
  for (const entry of await readdir(releaseRoot, { withFileTypes: true })) {
    if (entry.isDirectory() && validDirectory(entry.name)) {
      try { archived.push(await loadRelease(entry.name)); } catch { /* Never serve an incomplete release. */ }
    }
  }
  let active = bundled, previous = null, updatedAt = null, phase = 'idle', lastError = null, latest = null, checkedAt = 0, job = null;
  try {
    const state = JSON.parse(await readFile(stateFile, 'utf8'));
    if (validDirectory(state.previousDir)) {
      try { previous = await loadRelease(state.previousDir); } catch { /* The bundled copy is always available. */ }
    }
    try { active = await loadRelease(state.activeDir); updatedAt = state.updatedAt; }
    catch { active = previous ?? bundled; previous = bundled; lastError = 'Se recuperó la versión anterior del sistema.'; }
  } catch { /* A first installation starts with the verified bundled copy. */ }

  async function persist(next, old) {
    const time = new Date().toISOString();
    const temporary = join(storage, `state-${randomUUID()}.tmp`);
    await writeFile(temporary, JSON.stringify({ activeDir: next.name, previousDir: old.name, updatedAt: time }));
    await rename(temporary, stateFile);
    archived.push(old);
    previous = old; active = next; updatedAt = time;
  }
  async function responseBytes(response, maximum) {
    if (!response.ok || Number(response.headers.get('content-length') ?? 0) > maximum) throw new Error('No se pudo descargar la actualización completa.');
    const chunks = []; let size = 0;
    for await (const chunk of response.body) {
      size += chunk.length;
      if (size > maximum) throw new Error('La descarga supera el tamaño esperado.');
      chunks.push(chunk);
    }
    return Buffer.concat(chunks);
  }
  const get = (path, signal) => fetchImpl(new URL(path, sourceUrl), { cache: 'no-store', redirect: 'error', signal });
  async function download(manifest, signal) {
    const id = randomUUID(), stage = join(releaseRoot, id);
    let activated = false;
    await mkdir(stage);
    try {
      phase = 'downloading';
      for (const file of manifest.files) {
        const data = await responseBytes(await get(encodeURI(file.path.slice(1)), signal), file.size);
        if (data.length !== file.size || digest(data) !== file.sha256) throw new Error('La descarga no coincide con la versión publicada. Se conserva la versión anterior.');
        const target = join(stage, file.path.slice(1));
        await mkdir(dirname(target), { recursive: true });
        await writeFile(target, data);
      }
      await verifyReleaseDirectory(stage, manifest);
      await writeFile(join(stage, MANIFEST_NAME), JSON.stringify(manifest));
      await persist({ name: id, directory: stage, manifest }, active);
      activated = true;
      lastError = null; phase = 'idle';
    } finally {
      // Only remove the staging directory generated by this operation.
      if (!activated && dirname(resolve(stage)) === resolve(releaseRoot) && basename(stage) === id) {
        await rm(stage, { recursive: true, force: true });
      }
    }
  }
  async function exclusive(action) {
    if (job) return job;
    job = action().catch(error => {
      phase = 'error'; lastError = error instanceof Error ? error.message : 'No se pudo actualizar el sistema.';
      return false;
    }).finally(() => { job = null; });
    return job;
  }
  async function check({ autoApply = false, force = false } = {}) {
    if (job) await job;
    return exclusive(async () => {
      const signal = AbortSignal.timeout(timeoutMs);
      if (force || Date.now() - checkedAt > checkIntervalMs) {
        phase = 'checking';
        const data = await responseBytes(await get(`${MANIFEST_NAME}?check=${Date.now()}`, signal), 1024 * 1024);
        latest = validateManifest(JSON.parse(data.toString('utf8')));
        checkedAt = Date.now(); lastError = null;
      }
      if (latest && latest.version !== active.manifest.version) {
        if (autoApply) await download(latest, signal);
        else phase = 'available';
      } else phase = 'idle';
      return true;
    });
  }
  async function apply(expectedVersion) {
    if (job) await job;
    return exclusive(async () => {
      if (!latest || latest.version !== expectedVersion) throw new Error('La versión disponible cambió. Volvé a buscar actualizaciones.');
      if (latest.version !== active.manifest.version) await download(latest, AbortSignal.timeout(timeoutMs));
      return true;
    });
  }
  return {
    check, apply,
    status: () => ({ protocol: 1, app: APP_ID, active: summary(active.manifest), latest: latest ? summary(latest) : null, phase, lastError, updatedAt }),
    releases: () => [active, previous, bundled, ...archived].filter((release, index, releases) => release && releases.findIndex(item => item?.name === release.name) === index),
  };
}
