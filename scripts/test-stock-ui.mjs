import assert from 'node:assert/strict';
import { buildSync } from 'esbuild';
import { createRequire } from 'node:module';
import { runInNewContext } from 'node:vm';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
const compiled = buildSync({ stdin: { contents: `export {default as Form} from './src/components/ConsumableEditForm'; export {default as List} from './src/components/ConsumableList'; export {default as StockModal} from './src/components/StockModal'; export {AccessContext} from './src/config/AccessContext'; export {validateStock} from './src/utils/stock';`, resolveDir: process.cwd(), loader: 'tsx' }, bundle: true, write: false, format: 'cjs', platform: 'node', jsx: 'automatic', define: { 'import.meta.env': '{}' }, external: ['react', 'react-dom', 'lucide-react', '@supabase/supabase-js'] });
const module = { exports: {} };
runInNewContext(compiled.outputFiles[0].text, { module, exports: module.exports, require: createRequire(import.meta.url), console: { log() {}, error() {} } });
const { Form, List, AccessContext, StockModal, validateStock } = module.exports;
const product = { id: 'product', name: 'Agua', description: '', price: 100, category: 'drink', available: true };
const admin = { id: 'admin', role: 'admin' };
const render = (component, props, user = admin) => renderToStaticMarkup(React.createElement(AccessContext.Provider, { value: user }, React.createElement(component, props)));
const formProps = { categories: [], onSave() {}, onCancel() {}, onCategoriesUpdate() {} };
const fresh = render(Form, formProps);
assert.match(fresh, /value="false" selected=""/);
assert(!fresh.includes('Conteo inicial de unidades'));
const existing = render(Form, { ...formProps, consumable: product });
assert.match(existing, /value="false" selected=""/);
const controlled = { ...product, stockEnabled: true, stockQuantity: 2, stockMinimum: 3 };
const edited = render(Form, { ...formProps, consumable: controlled });
assert(edited.includes('Stock actual:')); assert(!edited.includes('Conteo inicial de unidades'));
const employee = render(Form, { ...formProps, consumable: product }, { role: 'employee', permissions: ['products.view','products.edit'] });
assert.match(employee, /name="stockEnabled"[^>]*disabled=""/);
const list = render(List, { consumables: [product, controlled], categories: [], sales: [], bookings: [], onEditConsumable() {}, onDeleteConsumable() {}, onAddConsumable() {}, async onStockChanged() {} });
assert(list.includes('Sin control')); assert(list.includes('Stock bajo'));
const empty = render(List, { consumables: [{ ...controlled, stockQuantity: 0 }], categories: [], sales: [], bookings: [], onEditConsumable() {}, onDeleteConsumable() {}, onAddConsumable() {}, async onStockChanged() {} });
assert(empty.includes('Sin stock'));
const disabledModal = render(StockModal, { product, onClose() {}, async onChanged() {} });
assert(disabledModal.includes('Control de stock: NO')); assert(!disabledModal.includes('Registrar movimiento'));
assert(disabledModal.includes('Controlar stock')); assert(disabledModal.includes('Guardar control de stock'));
const activeModal = render(StockModal, { product: controlled, onClose() {}, async onChanged() {} });
assert(activeModal.includes('Stock mínimo para alertas')); assert(activeModal.includes('Registrar movimiento'));
const readOnlyModal = render(StockModal, { product, onClose() {}, async onChanged() {} }, { role: 'employee', permissions: ['products.view'] });
assert(!readOnlyModal.includes('Guardar control de stock'));
const line = quantity => ({ consumableId: product.id, quantity });
assert.equal(validateStock([product], [line(999)]), null);
assert(validateStock([controlled], [line(3)]));
assert(validateStock([controlled], [line(2),line(1)]));
assert.equal(validateStock([controlled], [line(4)], [line(3)]), null);
assert.equal(validateStock([{ ...controlled, stockQuantity: 0 }], [line(3)], [line(3)]), null);
console.log('PASS: stock UI: NO by default, existing products, permissions, stock alerts, disabled movements and incremental validation.');
